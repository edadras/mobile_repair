# ------------------------------------------------------------- chipset groups

QUALCOMM = "qualcomm"
MEDIATEK = "mediatek"
SAMSUNG = "samsung"
UNKNOWN = "unknown"

# group name -> ordered candidate partitions (only those that exist are used)
GROUPS: Dict[str, Dict[str, List[str]]] = {
    QUALCOMM: {
        "modem-nv": ["modemst1", "modemst2", "fsg", "fsc"],
        "persist": ["persist", "persistbak"],
        "modem-fw": ["modem", "modem_a", "modem_b", "dsp", "bluetooth"],
    },
    MEDIATEK: {
        "modem-nv": ["nvram", "nvdata", "nvcfg", "protect1", "protect2", "nvram_only"],
        "persist": ["persist", "protect1", "protect2"],
        "modem-fw": ["md1img", "md1img_a", "md1img_b", "spmfw", "gz1"],
    },
    SAMSUNG: {
        "modem-nv": ["efs", "sec_efs", "cpefs", "modemst1", "modemst2", "fsg"],
        "persist": ["persist", "persistent"],
        "modem-fw": ["modem", "radio", "cp"],
    },
    UNKNOWN: {
        "modem-nv": ["modemst1", "modemst2", "fsg", "fsc", "efs", "sec_efs", "nvram", "nvdata", "nvcfg", "protect1", "protect2"],
        "persist": ["persist"],
        "modem-fw": ["modem", "radio", "dsp", "bluetooth", "md1img"],
    },
}

# mirror groups that must be restored together (any-order set)
QUALCOMM_MIRROR = ("modemst1", "modemst2", "fsg")
SAMSUNG_EFS_DIRS = ["/mnt/vendor/efs", "/efs", "/mnt/vendor/efs2"]


def detect_chipset(dev: AdbDevice) -> str:
    props = dev.getprops()
    blob = " ".join([
        props.get("ro.board.platform", ""), props.get("ro.hardware", ""),
        props.get("ro.boot.hardware", ""), props.get("ro.chipname", ""),
        props.get("ro.hardware.chipname", ""), props.get("ro.soc.manufacturer", ""),
    ]).lower()
    manuf = props.get("ro.product.manufacturer", "").lower()
    if any(x in blob for x in ("qcom", "msm", "sdm", "sm6", "sm7", "sm8", "lito", "kona", "taro", "kalama", "lahaina", "bengal", "holi", "trinket", "qualcomm")):
        return QUALCOMM
    if any(x in blob for x in ("mt6", "mt8", "mtk", "mediatek")):
        return MEDIATEK
    if any(x in blob for x in ("exynos", "universal", "s5e", "samsung")) or manuf == "samsung":
        return SAMSUNG
    return UNKNOWN


def resolve_group(dev: AdbDevice, chipset: str, group: str) -> List[part_mod.Partition]:
    parts = {p.name: p for p in part_mod.list_partitions(dev)}
    wanted = GROUPS.get(chipset, GROUPS[UNKNOWN]).get(group, [])
    resolved: List[part_mod.Partition] = []
    slot = dev.getprop("ro.boot.slot_suffix")
    for name in wanted:
        if name in parts:
            resolved.append(parts[name])
        elif slot and name + slot in parts:
            resolved.append(parts[name + slot])
    return resolved


# ------------------------------------------------------------------ backup


def backup(dev: AdbDevice, out_dir: str, safety: Safety, group: str = "modem-nv",
           chipset: str = "auto", include_efs_fs: bool = True) -> Dict[str, Any]:
    dev.ensure_root()
    if chipset == "auto":
        chipset = detect_chipset(dev)
    parts = resolve_group(dev, chipset, group)
    if not parts and not (chipset == SAMSUNG and include_efs_fs):
        raise MrtError(f"no partitions of group '{group}' found for chipset '{chipset}'. "
                       f"Run 'mrt efs detect' to see what exists.")
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    manifest: Dict[str, Any] = {
        "created": time.strftime("%Y-%m-%d %H:%M:%S"),
        "type": "mrt-efs-backup",
        "chipset": chipset,
        "group": group,
        "serial": dev.serial,
        "device": {k: dev.getprop(k) for k in ("ro.product.device", "ro.product.model", "ro.build.fingerprint", "ro.boot.slot_suffix")},
        "partitions": [],
    }
    info(f"chipset={chipset} group={group}: backing up {len(parts)} partition(s)")
    for p in parts:
        target = out / f"{p.name}.img"
        try:
            entry = part_mod.dump_partition(dev, p.name, str(target), verify=True)
            entry["status"] = "ok"
        except (MrtError, OSError) as exc:
            entry = {"partition": p.name, "status": "failed", "error": str(exc)}
            warn(f"{p.name}: {exc}")
        manifest["partitions"].append(entry)

    if chipset == SAMSUNG and include_efs_fs:
        manifest["efs_fs"] = _backup_samsung_efs_fs(dev, out)

    (out / "efs-manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    info(f"EFS backup written to {out}")
    return manifest


def _backup_samsung_efs_fs(dev: AdbDevice, out: Path) -> Dict[str, Any]:
    for d in SAMSUNG_EFS_DIRS:
        if dev.file_exists(d, root=True):
            tar_remote = f"/data/local/tmp/mrt_efs_{int(time.time())}.tar"
            dev.root_shell(f"tar -cf {tar_remote} -C {shlex.quote(d)} . 2>/dev/null && chmod 644 {tar_remote}", timeout=600)
            local = out / "efs_fs.tar"
            dev.pull(tar_remote, str(local), check=False)
            dev.root_shell(f"rm -f {tar_remote}", timeout=30)
            listing = dev.root_shell_text(f"ls -1 {shlex.quote(d)} 2>/dev/null | head -80").split("\n")
            return {"dir": d, "tar": str(local), "files": [x for x in listing if x.strip()]}
    return {"dir": None, "note": "no /efs filesystem found (partition-based EFS only)"}


# ------------------------------------------------------------------ restore


def restore(dev: AdbDevice, backup_dir: str, safety: Safety, group: Optional[str] = None,
            partitions: Optional[List[str]] = None, rollback: bool = True) -> Dict[str, Any]:
    dev.ensure_root()
    src = Path(backup_dir)
    man_path = src / "efs-manifest.json"
    if not man_path.exists():
        raise MrtError(f"not an mrt EFS backup (missing efs-manifest.json): {backup_dir}")
    manifest = json.loads(man_path.read_text(encoding="utf-8"))
    chipset = manifest.get("chipset", UNKNOWN)

    # device-identity guard
    cur_dev = dev.getprop("ro.product.device")
    bak_dev = (manifest.get("device") or {}).get("ro.product.device")
    if bak_dev and cur_dev and bak_dev != cur_dev:
        safety.confirm(
            f"This EFS backup was made on '{bak_dev}' but the connected device is '{cur_dev}'.\n"
            "Restoring another device's EFS/NV will corrupt the radio identity.",
            level=CRITICAL, token="MISMATCH")

    available = {e["partition"]: e for e in manifest["partitions"] if e.get("status") == "ok"}
    if partitions:
        chosen = [p for p in partitions if p in available]
        missing = [p for p in partitions if p not in available]
        if missing:
            warn(f"not in backup: {', '.join(missing)}")
    else:
        chosen = list(available)

    if not chosen:
        raise MrtError("nothing to restore (no matching partition images in the backup)")

    _warn_mirror(chipset, chosen)

    # pre-flight: every image exists and fits
    for name in chosen:
        img = src / f"{name}.img"
        if not img.exists():
            raise MrtError(f"missing image file: {img}")

    total = sum((src / f"{n}.img").stat().st_size for n in chosen)
    safety.confirm(
        f"RESTORE EFS/NV group ({chipset}) to {dev.serial or '(auto)'}:\n"
        f"  partitions: {', '.join(chosen)}\n"
        f"  total: {human_size(total)}\n"
        "These carry IMEI / MAC / RF calibration. A wrong restore corrupts the radio.\n"
        f"{'A rollback dump of the current content will be taken first.' if rollback else 'Rollback is DISABLED.'}",
        level=CRITICAL, token="RESTORE")

    result: Dict[str, Any] = {"chipset": chipset, "restored": {}, "rollback_dir": None}

    if rollback:
        rb = src / f"rollback-{time.strftime('%Y%m%d-%H%M%S')}"
        rb.mkdir(parents=True, exist_ok=True)
        info(f"taking rollback dump into {rb}")
        for name in chosen:
            try:
                part_mod.dump_partition(dev, name, str(rb / f"{name}.img"), verify=False)
            except MrtError as exc:
                warn(f"rollback dump of {name} failed: {exc}")
        result["rollback_dir"] = str(rb)

    for name in chosen:
        img = src / f"{name}.img"
        try:
            result["restored"][name] = part_mod.write_partition(dev, name, str(img), safety, allow_smaller=True)
        except (MrtError, VerificationFailed) as exc:
            result["restored"][name] = {"status": "FAILED", "error": str(exc)}
            warn(f"{name}: {exc}")
    info("restore complete; reboot the device and check IMEI / network registration")
    return result


def _warn_mirror(chipset: str, chosen: List[str]) -> None:
    if chipset in (QUALCOMM, SAMSUNG):
        if ("modemst1" in chosen) ^ ("modemst2" in chosen):
            warn("restoring only one of modemst1/modemst2: the modem may rebuild it from the other "
                 "mirror and lose your change. Restore both (and fsg) together.")
        if any(m in chosen for m in ("modemst1", "modemst2")) and "fsg" not in chosen:
            warn("fsg (the factory golden copy) is not being restored; if it disagrees with modemst "
                 "the modem may prefer it. Include fsg for a full atomic restore.")


# ----------------------------------------------------------------- validate


def validate(dev: AdbDevice, chipset: str = "auto", group: str = "modem-nv") -> Dict[str, Any]:
    dev.ensure_root()
    if chipset == "auto":
        chipset = detect_chipset(dev)
    parts = resolve_group(dev, chipset, group)
    report: Dict[str, Any] = {"chipset": chipset, "group": group, "partitions": [], "notes": []}
    hashes: Dict[str, Optional[str]] = {}
    for p in parts:
        state = _partition_state(dev, p)
        hashes[p.name] = state.get("sha256")
        report["partitions"].append(state)

    if chipset in (QUALCOMM, SAMSUNG) and "modemst1" in hashes and "modemst2" in hashes:
        report["mirror_modemst"] = {
            "modemst1": hashes["modemst1"], "modemst2": hashes["modemst2"],
            "identical": hashes["modemst1"] == hashes["modemst2"] and hashes["modemst1"] is not None,
            "note": "modemst1/modemst2 are a mirror pair; they are often (not always) identical. "
                    "If one is erased/empty and the other is not, restore the good one to both.",
        }
    report["notes"].append(
        "modemst/nvram are opaque EFS2/NVRAM filesystems: there is no partition-level checksum to "
        "recompute. Repair = atomic restore of the whole group from a good dump of THIS device.")

    if chipset == SAMSUNG:
        report["samsung_md5"] = _check_samsung_md5(dev)

    return report


def _partition_state(dev: AdbDevice, p: part_mod.Partition) -> Dict[str, Any]:
    dev_hash = dev.remote_sha256(p.device, root=True)
    # sample the first 1 MiB to classify erased/empty without reading the whole partition twice
    first = dev.root_shell_text(f"head -c 1048576 {shlex.quote(p.device)} | od -An -tx1 | tr -d ' \\n' | head -c 64")
    erased = bool(first) and (set(first) <= set("f") or set(first) <= set("0"))
    return {
        "partition": p.name, "device": p.device, "size": p.size, "size_h": p.size_h,
        "sha256": dev_hash,
        "state": "erased/empty" if erased else "populated",
    }


def _check_samsung_md5(dev: AdbDevice) -> Dict[str, Any]:
    for d in SAMSUNG_EFS_DIRS:
        if not dev.file_exists(d, root=True):
            continue
        names = [x for x in dev.root_shell_text(f"ls -1a {shlex.quote(d)} 2>/dev/null").split("\n") if x.strip()]
        targets = nvchecksum.samsung_md5_targets(names)
        rows = []
        for base in targets:
            base_path = f"{d}/{base}"
            md5_path = f"{base_path}.md5"
            actual = dev.remote_md5(base_path, root=True)
            stored = dev.root_shell_text(f"cat {shlex.quote(md5_path)} 2>/dev/null").strip().split()[0:1]
            stored_val = stored[0].lower() if stored else None
            rows.append({"file": base, "computed_md5": actual, "stored_md5": stored_val,
                         "match": bool(actual) and actual == stored_val})
        return {"dir": d, "files": rows}
    return {"dir": None, "note": "no /efs filesystem present"}


# ------------------------------------------------------- samsung md5 fix


def samsung_fix_md5(dev: Optional[AdbDevice], safety: Safety, efs_dir: Optional[str] = None,
                    local_dir: Optional[str] = None, create: bool = False) -> Dict[str, Any]:
    """Recompute Samsung nv_data MD5 sidecars so they match the current binary.

    ``local_dir``: fix a pulled copy on the host. Otherwise fix on the device
    (requires root); sidecars are rewritten as radio:radio to match the owner
    of the base file.
    """
    if local_dir:
        return _samsung_fix_local(local_dir, create)
    if dev is None:
        raise MrtError("device required when --local is not given")
    dev.ensure_root()
    target_dir = efs_dir
    if not target_dir:
        for d in SAMSUNG_EFS_DIRS:
            if dev.file_exists(d, root=True):
                target_dir = d
                break
    if not target_dir or not dev.file_exists(target_dir, root=True):
        raise MrtError("no Samsung /efs filesystem found (this device may use a partition-based EFS)")

    names = [x for x in dev.root_shell_text(f"ls -1a {shlex.quote(target_dir)} 2>/dev/null").split("\n") if x.strip()]
    targets = nvchecksum.samsung_md5_targets(names)
    if create:
        for b, m in nvchecksum.SAMSUNG_MD5_PAIRS:
            if b and not b.endswith(".md5") and b in names and b not in targets:
                targets.append(b)
    if not targets:
        return {"dir": target_dir, "changed": [], "note": "no nv_data files with md5 sidecars found"}

    safety.confirm(f"Recompute MD5 sidecars in {target_dir} on the device for: {', '.join(targets)}",
                   level=DESTRUCTIVE)
    changed = []
    for base in targets:
        base_path = f"{target_dir}/{base}"
        md5_path = f"{base_path}.md5"
        computed = dev.remote_md5(base_path, root=True)
        if not computed:
            warn(f"cannot read {base_path}")
            continue
        stored = dev.root_shell_text(f"cat {shlex.quote(md5_path)} 2>/dev/null").strip().split()[0:1]
        if stored and stored[0].lower() == computed:
            continue
        owner = dev.root_shell_text(f"stat -c '%U:%G' {shlex.quote(base_path)} 2>/dev/null").strip() or "radio:radio"
        dev.root_shell(f"printf %s {computed} > {shlex.quote(md5_path)} && chown {owner} {shlex.quote(md5_path)} && chmod 600 {shlex.quote(md5_path)}", timeout=60)
        changed.append({"file": base, "md5": computed, "owner": owner})
    info(f"fixed {len(changed)} sidecar(s); reboot to let the modem re-read /efs")
    return {"dir": target_dir, "changed": changed}


def _samsung_fix_local(local_dir: str, create: bool) -> Dict[str, Any]:
    d = Path(local_dir)
    if not d.is_dir():
        raise MrtError(f"not a directory: {local_dir}")
    names = [p.name for p in d.iterdir()]
    targets = nvchecksum.samsung_md5_targets(names)
    if create:
        for b, _m in nvchecksum.SAMSUNG_MD5_PAIRS:
            if b and not b.endswith(".md5") and b in names and b not in targets:
                targets.append(b)
    changed = []
    for base in targets:
        data = (d / base).read_bytes()
        md5 = nvchecksum.samsung_md5_hex(data)
        sidecar = d / f"{base}.md5"
        old = sidecar.read_text(encoding="utf-8").strip() if sidecar.exists() else None
        if old and old.lower() == md5:
            continue
        sidecar.write_text(md5, encoding="utf-8")
        changed.append({"file": base, "md5": md5})
    return {"dir": str(d), "changed": changed}
