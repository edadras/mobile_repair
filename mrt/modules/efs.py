"""EFS / NV (modem identity) backup, restore, validation and repair.

This module deals with the partitions that carry a phone's radio identity and
calibration - IMEI, MAC addresses, per-device RF calibration, SIM-lock state:

* **Qualcomm**: ``modemst1`` + ``modemst2`` (a mirrored EFS2 pair) + ``fsg``
  (the factory "golden" copy) + ``fsc``. These MUST be handled as one atomic
  group - restoring only one of the mirror pair lets the modem rebuild from the
  other and silently lose your change.
* **MediaTek**: ``nvram`` + ``nvdata`` + ``nvcfg`` + ``protect1`` + ``protect2``.
* **Samsung/Exynos**: an ``efs``/``sec_efs`` partition and/or an ``/efs``
  filesystem containing ``nv_data.bin`` guarded by an MD5 sidecar.

Checksums, honestly (see :mod:`mrt.utils.efs2`, :mod:`mrt.utils.mtknv`,
:mod:`mrt.utils.nvchecksum`): Qualcomm EFS2 (``modemst``/``fsg``) has **no**
CRC field in its superblock or pages, and MediaTek ``nvdata`` is ext4 while
``nvram`` is a backup region written by ``nvram_daemon``. Their integrity data
is owned and regenerated by the firmware, so this module does not fake a
"CRC fix". It does the two things that are real: (1) verify the structures
offline / on-device (:func:`analyze_image`, :func:`check_images`,
:func:`validate`) and (2) make the firmware rebuild them - erase the
``modemst`` mirror so the modem re-creates it from ``fsg``
(:func:`rebuild_modemst`), or empty ``nvdata`` so ``nvram_daemon`` restores
every file from the ``nvram`` backup (:func:`mtk_rebuild_nvdata`) - both only
after a fresh backup and only when the source copy verifies. The one genuine
hand-recomputable checksum, Samsung's ``nv_data.bin.md5``, is regenerated by
:func:`samsung_fix_md5`. Writing NV items or a QCN back onto the modem needs
a DIAG port (QPST/QFIL) and is not possible over adb.
"""

