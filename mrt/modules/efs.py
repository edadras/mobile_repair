"""EFS / NV (modem identity) backup, restore, validation and repair.

This module deals with the partitions that carry a phone's radio identity and
calibration - IMEI, MAC addresses, per-device RF calibration, SIM-lock state:

* **Qualcomm**: ``modemst1`` + ``modemst2`` (a mirrored EFS2 pair) + ``fsg``
  (the factory "golden" copy) + ``fsc``. These MUST be handled as one atomic
  group - restoring only one of the mirror pair lets the modem rebuild from the
  other and silently lose your change.
* **MediaTek**: ``nvram`` + ``nvdata`` + ``nvcfg`` + ``protect1`` + ``protect2``.
* **Samsung/Exynos**: an ``efs``/``sec_efs`` partition and/or an ``/efs``
  filesystem containing ``nv_data.bin`` guarded by an MD5 sidecar.

Honest boundaries (see :mod:`mrt.utils.nvchecksum`): the internal EFS2 / NVRAM
filesystems have no user-recomputable partition checksum, so this module does
NOT pretend to "fix the CRC" of ``modemst``/``nvram`` - it restores the group
atomically from a verified dump instead. The one genuine recomputable checksum,
Samsung's ``nv_data.bin.md5``, is regenerated by :func:`samsung_fix_md5`.
Writing NV items or a QCN back onto the modem needs a DIAG port (QPST/QFIL) and
is not possible over adb.
"""

from __future__ import annotations

import json
import os
import shlex
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from ..core.device import AdbDevice
